export function createNewVectorLayer(
  kind: VectorShapeKind,
  index: number,
  compCenter: { x: number; y: number }
): VectorLayer2D {
  const palette = ['#0EA5E9', '#F59E0B', '#10B981', '#EC4899', '#8B5CF6', '#38BDF8'];
  const color = palette[index % palette.length];
  const labelMap: Record<VectorShapeKind, string> = {
    rect: 'Rounded_Rect',
    ellipse: 'Ellipse_Orb',
    polygon: 'Polygon_Star',
    path: 'Bezier_Curve',
  };

  return {
    id: `layer-${Date.now()}-${Math.floor(Math.random() * 1000)}`,
    name: `${labelMap[kind]}_${index + 1}`,
    parentId: null,
    kind,
    width: kind === 'rect' ? 120 : 96,
    height: kind === 'rect' ? 68 : 96,
    cornerRadius: kind === 'rect' ? 16 : 0,
    sides: 5,
    closed: kind !== 'path',
    vertices:
      kind === 'path'
        ? [
            { x: -55, y: 20, inX: 0, inY: 0, outX: 25, outY: -45 },
            { x: 0, y: -20, inX: -22, inY: 0, outX: 22, outY: 0 },
            { x: 55, y: 20, inX: -25, inY: -45, outX: 0, outY: 0 },
          ]
        : [],
    fillColor: color,
    fillOpacity: kind === 'path' ? 0 : 0.95,
    strokeColor: '#F8FAFC',
    strokeWidth: kind === 'path' ? 5 : 2.5,
    inpaintCap: false,
    anchor: { x: 0, y: 0 },
    positionTrack: [
      {
        frame: 0,
        x: compCenter.x + ((index % 3) - 1) * 28,
        y: compCenter.y + ((index % 2) - 0.5) * 24,
        easing: 'easeInOut',
      },
    ],
    rotationTrack: [{ frame: 0, value: 0, easing: 'easeInOut' }],
    scaleTrack: [{ frame: 0, x: 100, y: 100, easing: 'easeInOut' }],
    opacityTrack: [{ frame: 0, value: 100, easing: 'linear' }],
    visible: true,
    locked: false,
  };
}
